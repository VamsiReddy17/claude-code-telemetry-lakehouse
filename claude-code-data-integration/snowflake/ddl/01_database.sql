-- Snowflake: database, warehouse, role skeleton
-- Run as ACCOUNTADMIN / SYSADMIN then grant down.

CREATE WAREHOUSE IF NOT EXISTS CLAUDE_TELEM_WH
  WITH WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS CLAUDE_TELEMETRY;
CREATE SCHEMA IF NOT EXISTS CLAUDE_TELEMETRY.BRONZE;
CREATE SCHEMA IF NOT EXISTS CLAUDE_TELEMETRY.SILVER;
CREATE SCHEMA IF NOT EXISTS CLAUDE_TELEMETRY.GOLD;

CREATE ROLE IF NOT EXISTS CLAUDE_TELEM_ROLE;
GRANT USAGE ON WAREHOUSE CLAUDE_TELEM_WH TO ROLE CLAUDE_TELEM_ROLE;
GRANT USAGE ON DATABASE CLAUDE_TELEMETRY TO ROLE CLAUDE_TELEM_ROLE;
GRANT USAGE, CREATE TABLE, CREATE STAGE, CREATE PIPE ON SCHEMA CLAUDE_TELEMETRY.BRONZE TO ROLE CLAUDE_TELEM_ROLE;
GRANT USAGE, CREATE TABLE ON SCHEMA CLAUDE_TELEMETRY.SILVER TO ROLE CLAUDE_TELEM_ROLE;
GRANT USAGE, CREATE TABLE ON SCHEMA CLAUDE_TELEMETRY.GOLD TO ROLE CLAUDE_TELEM_ROLE;

