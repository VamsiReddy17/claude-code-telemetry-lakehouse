-- Silver / gold tables in Snowflake
-- Path A: filled by Snowpipe + TASKS from BRONZE.OTEL_RAW
-- Path B: overwritten by Databricks spark-snowflake sync (gold only)

USE DATABASE CLAUDE_TELEMETRY;

CREATE OR REPLACE TABLE SILVER.PROMPTS (
  PROMPT_SK STRING,
  SESSION_ID STRING,
  PROMPT_ID STRING,
  EVENT_SEQUENCE NUMBER,
  EVENT_TIMESTAMP TIMESTAMP_NTZ,
  USER_ACCOUNT_UUID STRING,
  PROMPT_TEXT STRING,
  PROMPT_LENGTH NUMBER,
  ORG_ID STRING
);

CREATE OR REPLACE TABLE SILVER.RESPONSES (
  RESPONSE_SK STRING,
  SESSION_ID STRING,
  PROMPT_ID STRING,
  MESSAGE_UUID STRING,
  EVENT_SEQUENCE NUMBER,
  EVENT_TIMESTAMP TIMESTAMP_NTZ,
  RESPONSE_TEXT STRING,
  RESPONSE_LENGTH NUMBER,
  MODEL STRING,
  ORG_ID STRING
);

CREATE OR REPLACE TABLE SILVER.TOOL_EVENTS (
  TOOL_EVENT_SK STRING,
  SESSION_ID STRING,
  PROMPT_ID STRING,
  EVENT_NAME STRING,
  TOOL_NAME STRING,
  TOOL_INPUT STRING,
  TOOL_OUTPUT STRING,
  DECISION STRING,
  EVENT_TIMESTAMP TIMESTAMP_NTZ,
  ORG_ID STRING
);

CREATE OR REPLACE TABLE SILVER.SESSIONS (
  SESSION_ID STRING,
  ORG_ID STRING,
  USER_ACCOUNT_UUID STRING,
  STARTED_AT TIMESTAMP_NTZ,
  LAST_EVENT_AT TIMESTAMP_NTZ,
  PROMPT_COUNT NUMBER,
  RESPONSE_COUNT NUMBER,
  TOOL_CALL_COUNT NUMBER,
  TOTAL_INPUT_TOKENS NUMBER,
  TOTAL_OUTPUT_TOKENS NUMBER,
  TOTAL_COST_USD FLOAT
);

CREATE OR REPLACE TABLE GOLD.DAILY_USER_USAGE (
  USAGE_DATE DATE,
  ORG_ID STRING,
  USER_ACCOUNT_UUID STRING,
  SESSIONS NUMBER,
  PROMPTS NUMBER,
  RESPONSES NUMBER,
  TOOL_EVENTS NUMBER,
  INPUT_TOKENS NUMBER,
  OUTPUT_TOKENS NUMBER,
  COST_USD FLOAT
);

CREATE OR REPLACE TABLE GOLD.COMPLIANCE_TRANSCRIPT_LINES (
  ORG_ID STRING,
  SESSION_ID STRING,
  USER_ACCOUNT_UUID STRING,
  PROMPT_TS TIMESTAMP_NTZ,
  PROMPT_TEXT STRING,
  RESPONSE_TS TIMESTAMP_NTZ,
  RESPONSE_TEXT STRING,
  MODEL STRING
);

CREATE OR REPLACE VIEW GOLD.V_DAILY_ORG_USAGE AS
SELECT
  USAGE_DATE,
  ORG_ID,
  SUM(SESSIONS) AS SESSIONS,
  SUM(PROMPTS) AS PROMPTS,
  SUM(RESPONSES) AS RESPONSES,
  SUM(TOOL_EVENTS) AS TOOL_EVENTS,
  SUM(INPUT_TOKENS) AS INPUT_TOKENS,
  SUM(OUTPUT_TOKENS) AS OUTPUT_TOKENS,
  SUM(COST_USD) AS COST_USD
FROM GOLD.DAILY_USER_USAGE
GROUP BY 1, 2;
