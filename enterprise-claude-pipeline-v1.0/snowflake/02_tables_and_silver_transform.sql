USE DATABASE CLAUDE_CODE_ANALYTICS;
USE SCHEMA SILVER;

-- 1. Silver Relational Tables
CREATE TABLE IF NOT EXISTS SILVER.PROMPTS (
  SESSION_ID VARCHAR(128),
  USER_EMAIL VARCHAR(256),
  DEPARTMENT VARCHAR(128),
  EVENT_TIMESTAMP TIMESTAMP_NTZ,
  MODEL_NAME VARCHAR(128),
  PROMPT_TEXT VARCHAR,
  PROMPT_TOKENS NUMBER,
  PROCESSED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS SILVER.RESPONSES (
  SESSION_ID VARCHAR(128),
  USER_EMAIL VARCHAR(256),
  EVENT_TIMESTAMP TIMESTAMP_NTZ,
  MODEL_NAME VARCHAR(128),
  RESPONSE_TEXT VARCHAR,
  COMPLETION_TOKENS NUMBER,
  LATENCY_MS NUMBER,
  PROCESSED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS SILVER.TOOL_EXECUTIONS (
  SESSION_ID VARCHAR(128),
  USER_EMAIL VARCHAR(256),
  EVENT_TIMESTAMP TIMESTAMP_NTZ,
  TOOL_NAME VARCHAR(128),
  TOOL_INPUT VARCHAR,
  TOOL_OUTPUT VARCHAR,
  DURATION_MS NUMBER,
  EXIT_CODE NUMBER,
  PROCESSED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS SILVER.SESSIONS (
  SESSION_ID VARCHAR(128) PRIMARY KEY,
  USER_EMAIL VARCHAR(256),
  DEPARTMENT VARCHAR(128),
  SESSION_START TIMESTAMP_NTZ,
  SESSION_END TIMESTAMP_NTZ,
  TOTAL_PROMPTS NUMBER,
  TOTAL_TOOL_CALLS NUMBER,
  SESSION_DURATION_SEC NUMBER,
  PROCESSED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS SILVER.TOKEN_COSTS (
  SESSION_ID VARCHAR(128),
  USER_EMAIL VARCHAR(256),
  DEPARTMENT VARCHAR(128),
  EVENT_TIMESTAMP TIMESTAMP_NTZ,
  MODEL_NAME VARCHAR(128),
  INPUT_TOKENS NUMBER,
  OUTPUT_TOKENS NUMBER,
  CACHE_CREATION_TOKENS NUMBER,
  CACHE_READ_TOKENS NUMBER,
  ESTIMATED_COST_USD NUMBER(10,4),
  PROCESSED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- 2. Snowflake Stream on Bronze Raw Telemetry
CREATE OR REPLACE STREAM BRONZE.RAW_TELEMETRY_STREAM ON TABLE BRONZE.RAW_TELEMETRY;

-- 3. Snowflake Task for Continuous Processing from Bronze to Silver
CREATE OR REPLACE TASK SILVER.TASK_PROCESS_RAW_TO_SILVER
  WAREHOUSE = 'COMPUTE_WH'
  SCHEDULE = '5 MINUTE'
  WHEN SYSTEM$STREAM_HAS_DATA('BRONZE.RAW_TELEMETRY_STREAM')
AS
BEGIN

  -- Insert Prompts
  INSERT INTO SILVER.PROMPTS (SESSION_ID, USER_EMAIL, DEPARTMENT, EVENT_TIMESTAMP, MODEL_NAME, PROMPT_TEXT, PROMPT_TOKENS)
  SELECT
    RAW_PAYLOAD:body:attributes:session:id::VARCHAR,
    RAW_PAYLOAD:body:attributes:user:email::VARCHAR,
    RAW_PAYLOAD:body:attributes:org:department::VARCHAR,
    RAW_PAYLOAD:body:timestamp::TIMESTAMP_NTZ,
    RAW_PAYLOAD:body:attributes:model:name::VARCHAR,
    RAW_PAYLOAD:body:attributes:prompt:text::VARCHAR,
    RAW_PAYLOAD:body:attributes:prompt:token_count::NUMBER
  FROM BRONZE.RAW_TELEMETRY_STREAM
  WHERE RAW_PAYLOAD:body:name::VARCHAR = 'claude_code.user_prompt';

  -- Insert Tool Executions
  INSERT INTO SILVER.TOOL_EXECUTIONS (SESSION_ID, USER_EMAIL, EVENT_TIMESTAMP, TOOL_NAME, TOOL_INPUT, TOOL_OUTPUT, DURATION_MS, EXIT_CODE)
  SELECT
    RAW_PAYLOAD:body:attributes:session:id::VARCHAR,
    RAW_PAYLOAD:body:attributes:user:email::VARCHAR,
    RAW_PAYLOAD:body:timestamp::TIMESTAMP_NTZ,
    RAW_PAYLOAD:body:attributes:tool:name::VARCHAR,
    RAW_PAYLOAD:body:attributes:tool:input::VARCHAR,
    RAW_PAYLOAD:body:attributes:tool:output::VARCHAR,
    RAW_PAYLOAD:body:attributes:tool:duration_ms::NUMBER,
    RAW_PAYLOAD:body:attributes:tool:exit_code::NUMBER
  FROM BRONZE.RAW_TELEMETRY_STREAM
  WHERE RAW_PAYLOAD:body:name::VARCHAR IN ('claude_code.tool_decision', 'claude_code.tool_result');

  -- Insert Token Costs
  INSERT INTO SILVER.TOKEN_COSTS (SESSION_ID, USER_EMAIL, DEPARTMENT, EVENT_TIMESTAMP, MODEL_NAME, INPUT_TOKENS, OUTPUT_TOKENS, CACHE_CREATION_TOKENS, CACHE_READ_TOKENS, ESTIMATED_COST_USD)
  SELECT
    RAW_PAYLOAD:body:attributes:session:id::VARCHAR,
    RAW_PAYLOAD:body:attributes:user:email::VARCHAR,
    RAW_PAYLOAD:body:attributes:org:department::VARCHAR,
    RAW_PAYLOAD:body:timestamp::TIMESTAMP_NTZ,
    RAW_PAYLOAD:body:attributes:model:name::VARCHAR,
    NVL(RAW_PAYLOAD:body:attributes:tokens:input::NUMBER, 0),
    NVL(RAW_PAYLOAD:body:attributes:tokens:output::NUMBER, 0),
    NVL(RAW_PAYLOAD:body:attributes:tokens:cache_creation::NUMBER, 0),
    NVL(RAW_PAYLOAD:body:attributes:tokens:cache_read::NUMBER, 0),
    (NVL(RAW_PAYLOAD:body:attributes:tokens:input::NUMBER, 0) * 0.000003) +
    (NVL(RAW_PAYLOAD:body:attributes:tokens:output::NUMBER, 0) * 0.000015) +
    (NVL(RAW_PAYLOAD:body:attributes:tokens:cache_creation::NUMBER, 0) * 0.00000375) +
    (NVL(RAW_PAYLOAD:body:attributes:tokens:cache_read::NUMBER, 0) * 0.00000030)
  FROM BRONZE.RAW_TELEMETRY_STREAM
  WHERE RAW_PAYLOAD:body:name::VARCHAR = 'claude_code.assistant_response';

END;

-- Resume Task Execution
ALTER TASK SILVER.TASK_PROCESS_RAW_TO_SILVER RESUME;
