USE DATABASE CLAUDE_CODE_ANALYTICS;
USE SCHEMA GOLD;

-- ----------------------------------------------------------------------------
-- 1. Executive Daily KPI View
-- ----------------------------------------------------------------------------
CREATE OR REPLACE VIEW GOLD.V_EXECUTIVE_DAILY_KPIS AS
SELECT
  DATE_TRUNC('DAY', EVENT_TIMESTAMP) AS METRIC_DATE,
  COUNT(DISTINCT USER_EMAIL) AS ACTIVE_DEVELOPERS_DAU,
  COUNT(DISTINCT SESSION_ID) AS TOTAL_SESSIONS,
  SUM(INPUT_TOKENS + OUTPUT_TOKENS + CACHE_CREATION_TOKENS + CACHE_READ_TOKENS) AS TOTAL_TOKENS_CONSUMED,
  ROUND(SUM(ESTIMATED_COST_USD), 2) AS TOTAL_SPEND_USD,
  ROUND(SUM(ESTIMATED_COST_USD) / NULLIF(COUNT(DISTINCT USER_EMAIL), 0), 2) AS AVG_SPEND_PER_DEV_USD
FROM SILVER.TOKEN_COSTS
GROUP BY 1
ORDER BY METRIC_DATE DESC;

-- ----------------------------------------------------------------------------
-- 2. Tool Adoption & Execution Matrix View
-- ----------------------------------------------------------------------------
CREATE OR REPLACE VIEW GOLD.V_TOOL_ADOPTION_MATRIX AS
SELECT
  DATE_TRUNC('DAY', EVENT_TIMESTAMP) AS METRIC_DATE,
  TOOL_NAME,
  COUNT(*) AS TOTAL_EXECUTIONS,
  COUNT(DISTINCT USER_EMAIL) AS UNIQUE_USERS,
  SUM(CASE WHEN EXIT_CODE != 0 THEN 1 ELSE 0 END) AS FAILED_EXECUTIONS,
  ROUND((SUM(CASE WHEN EXIT_CODE != 0 THEN 1 ELSE 0 END) / COUNT(*)) * 100, 2) AS ERROR_RATE_PCT,
  ROUND(AVG(DURATION_MS), 2) AS AVG_DURATION_MS
FROM SILVER.TOOL_EXECUTIONS
GROUP BY 1, 2
ORDER BY METRIC_DATE DESC, TOTAL_EXECUTIONS DESC;

-- ----------------------------------------------------------------------------
-- 3. Departmental Cost Attribution & Token Economics View
-- ----------------------------------------------------------------------------
CREATE OR REPLACE VIEW GOLD.V_DEPARTMENT_COST_ATTRIBUTION AS
SELECT
  DATE_TRUNC('DAY', EVENT_TIMESTAMP) AS METRIC_DATE,
  NVL(DEPARTMENT, 'Unassigned') AS DEPARTMENT,
  MODEL_NAME,
  COUNT(DISTINCT USER_EMAIL) AS ACTIVE_USERS,
  SUM(INPUT_TOKENS) AS TOTAL_INPUT_TOKENS,
  SUM(OUTPUT_TOKENS) AS TOTAL_OUTPUT_TOKENS,
  SUM(CACHE_READ_TOKENS) AS TOTAL_CACHE_READ_TOKENS,
  ROUND(SUM(ESTIMATED_COST_USD), 2) AS TOTAL_COST_USD
FROM SILVER.TOKEN_COSTS
GROUP BY 1, 2, 3
ORDER BY METRIC_DATE DESC, TOTAL_COST_USD DESC;

-- ----------------------------------------------------------------------------
-- 4. Security Leak Audit View
-- ----------------------------------------------------------------------------
CREATE OR REPLACE VIEW GOLD.V_SECURITY_LEAK_AUDIT AS
SELECT
  DATE_TRUNC('DAY', EVENT_TIMESTAMP) AS AUDIT_DATE,
  EVENT_TIMESTAMP,
  USER_EMAIL,
  DEPARTMENT,
  SESSION_ID,
  PROMPT_TEXT AS FLAGGED_CONTENT_SNIPPET
FROM SILVER.PROMPTS
WHERE PROMPT_TEXT LIKE '%[REDACTED_%'
ORDER BY EVENT_TIMESTAMP DESC;

-- ============================================================================
-- Security & Role-Based Access Control (RBAC) Setup
-- ============================================================================

USE ROLE ACCOUNTADMIN;

-- Role 1: Executive BI Role (Aggregated views only - NO raw prompt text access)
CREATE ROLE IF NOT EXISTS EXECUTIVE_BI_ROLE;
GRANT USAGE ON DATABASE CLAUDE_CODE_ANALYTICS TO ROLE EXECUTIVE_BI_ROLE;
GRANT USAGE ON SCHEMA CLAUDE_CODE_ANALYTICS.GOLD TO ROLE EXECUTIVE_BI_ROLE;
GRANT SELECT ON VIEW CLAUDE_CODE_ANALYTICS.GOLD.V_EXECUTIVE_DAILY_KPIS TO ROLE EXECUTIVE_BI_ROLE;
GRANT SELECT ON VIEW CLAUDE_CODE_ANALYTICS.GOLD.V_TOOL_ADOPTION_MATRIX TO ROLE EXECUTIVE_BI_ROLE;
GRANT SELECT ON VIEW CLAUDE_CODE_ANALYTICS.GOLD.V_DEPARTMENT_COST_ATTRIBUTION TO ROLE EXECUTIVE_BI_ROLE;

-- Role 2: Security & Compliance Audit Role (Access to Security Leak Audit View)
CREATE ROLE IF NOT EXISTS SECURITY_AUDIT_ROLE;
GRANT USAGE ON DATABASE CLAUDE_CODE_ANALYTICS TO ROLE SECURITY_AUDIT_ROLE;
GRANT USAGE ON SCHEMA CLAUDE_CODE_ANALYTICS.GOLD TO ROLE SECURITY_AUDIT_ROLE;
GRANT USAGE ON SCHEMA CLAUDE_CODE_ANALYTICS.SILVER TO ROLE SECURITY_AUDIT_ROLE;
GRANT SELECT ON VIEW CLAUDE_CODE_ANALYTICS.GOLD.V_SECURITY_LEAK_AUDIT TO ROLE SECURITY_AUDIT_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA CLAUDE_CODE_ANALYTICS.SILVER TO ROLE SECURITY_AUDIT_ROLE;

-- Role 3: Data Engineering Role (Full operational management)
CREATE ROLE IF NOT EXISTS DATA_ENGINEERING_ROLE;
GRANT ALL PRIVILEGES ON DATABASE CLAUDE_CODE_ANALYTICS TO ROLE DATA_ENGINEERING_ROLE;
GRANT ALL PRIVILEGES ON ALL SCHEMAS IN DATABASE CLAUDE_CODE_ANALYTICS TO ROLE DATA_ENGINEERING_ROLE;

